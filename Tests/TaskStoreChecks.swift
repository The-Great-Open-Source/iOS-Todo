import Foundation

final class MemoryMirror: SnapshotMirror {
    var data: Data?
    func write(_ data: Data) { self.data = data }
    func read() -> Data? { data }
}

@main
struct TaskStoreChecks {
    @MainActor static func main() throws {
        precondition(CompletionMilestone.crossed(before: 0, after: 1, total: 4) == .quarter)
        precondition(CompletionMilestone.crossed(before: 1, after: 2, total: 4) == .half)
        precondition(CompletionMilestone.crossed(before: 2, after: 3, total: 4) == .threeQuarters)
        precondition(CompletionMilestone.crossed(before: 3, after: 4, total: 4) == .complete)
        precondition(CompletionMilestone.crossed(before: 0, after: 1, total: 1) == .complete)
        precondition(CompletionMilestone.crossed(before: 0, after: 1, total: 3) == .quarter)
        precondition(CompletionMilestone.crossed(before: 1, after: 2, total: 3) == .half)
        precondition(CompletionMilestone.crossed(before: 2, after: 3, total: 3) == .complete)
        precondition(CompletionMilestone.crossed(before: 1, after: 0, total: 4) == nil)
        precondition(CompletionMilestone.crossed(before: 1, after: 1, total: 4) == nil)
        precondition(CompletionMilestone.crossed(before: 0, after: 0, total: 0) == nil)
        precondition(CompletionMilestone.crossed(before: 0, after: 1, total: 10) == nil)
        print("PASS: 25/50/75/100 milestone crossings, small lists, reopening, unchanged counts, empty lists")

        // Celebrations fire once per run of wins, and adding new work re-arms them.
        var ledger = CelebrationLedger()
        precondition(ledger.claim(before: 0, after: 1, total: 4, category: "a") == .quarter)
        precondition(ledger.claim(before: 0, after: 1, total: 4, category: "a") == nil)
        precondition(ledger.claim(before: 0, after: 1, total: 4, category: "b") == .quarter)
        precondition(ledger.claim(before: 3, after: 4, total: 4, category: "a") == .complete)
        precondition(ledger.claim(before: 3, after: 4, total: 4, category: "a") == nil)
        ledger.rearm(category: "a")
        precondition(ledger.claim(before: 4, after: 5, total: 5, category: "a") == .complete)
        precondition(ledger.hasCelebrated(.complete, category: "b") == false)
        precondition(CompletionMilestone.allCases.map(\.impactTime) == CompletionMilestone.allCases.map(\.impactTime).sorted())
        print("PASS: celebration ledger plays each milestone once, per category, and re-arms when new tasks arrive")

        let undoStore = TaskStore(persistence: TaskPersistence(url: URL.temporaryDirectory.appendingPathComponent("TodosUndo-\(UUID()).json")))
        if let first = undoStore.tasks.first {
            undoStore.delete(first)
            precondition(undoStore.deletedTask != nil)
            undoStore.dismissUndo()
            precondition(undoStore.deletedTask == nil && undoStore.deletedCategory == nil)
        }
        print("PASS: undo banner state clears when dismissed")

        precondition(CategoryIcon.suggest(for: "Groceries") == "cart")
        precondition(CategoryIcon.suggest(for: "  WORK  ") == "briefcase")
        precondition(CategoryIcon.suggest(for: "Gym & recovery") == "dumbbell")
        precondition(CategoryIcon.suggest(for: "Travel ideas") == "airplane")
        precondition(CategoryIcon.suggest(for: "Kavindu") == "k.circle")
        precondition(CategoryIcon.suggest(for: "2027") == "2.circle")
        precondition(CategoryIcon.suggest(for: "සතිය") != CategoryIcon.legacyDefault)
        precondition(CategoryIcon.suggest(for: "සතිය") == CategoryIcon.suggest(for: "සතිය"))
        let iconURL = URL.temporaryDirectory.appendingPathComponent("TodosIcons-\(UUID()).json")
        defer { try? FileManager.default.removeItem(at: iconURL) }
        let iconStore = TaskStore(persistence: TaskPersistence(url: iconURL))
        precondition(iconStore.addCategory(title: "Groceries"))
        let groceries = iconStore.categories.last!
        precondition(groceries.symbol == "cart")
        precondition(iconStore.renameCategory(groceries, title: "Bills"))
        precondition(iconStore.categories.last!.symbol == "creditcard")
        precondition(TaskStore(persistence: TaskPersistence(url: iconURL)).categories.last!.symbol == "creditcard")
        let oldIconURL = URL.temporaryDirectory.appendingPathComponent("TodosLegacyIcons-\(UUID()).json")
        defer { try? FileManager.default.removeItem(at: oldIconURL) }
        let oldIconPersistence = TaskPersistence(url: oldIconURL)
        try oldIconPersistence.save(TaskSnapshot(tasks: [], categories: [.today, TaskCategory(rawValue: "g", title: "Gym", symbol: CategoryIcon.legacyDefault)]))
        precondition(TaskStore(persistence: oldIconPersistence).categories.last!.symbol == "dumbbell")
        let migratedSymbol = try oldIconPersistence.loadSnapshot().categories.last!.symbol
        precondition(migratedSymbol == "dumbbell")
        print("PASS: category icons are suggested from names, update on rename, and replace the old generic icon once")

        let folder = URL.temporaryDirectory.appendingPathComponent("TodosChecks-\(UUID())")
        defer { try? FileManager.default.removeItem(at: folder) }
        let persistence = TaskPersistence(url: folder.appendingPathComponent("tasks.json"))
        let starterPersistence = TaskPersistence(url: folder.appendingPathComponent("starter.json"))
        let starter = TaskStore(persistence: starterPersistence)
        precondition(starter.items(in: .today).count == 4)
        precondition(starter.items(in: .work).isEmpty && starter.items(in: .personal).isEmpty)
        precondition(starter.tasks.allSatisfy { !$0.isCompleted })
        precondition(TaskStore(persistence: starterPersistence).tasks == starter.tasks)
        for task in starter.tasks { starter.delete(task) }
        precondition(TaskStore(persistence: starterPersistence).tasks.isEmpty)
        print("PASS: Today starter tasks persist once and stay deleted after restart")

        try persistence.save([])
        let store = TaskStore(persistence: persistence)
        precondition(store.tasks.isEmpty)
        precondition(store.categories == [.today])
        precondition(store.addCategory(title: "Work"))
        precondition(store.addCategory(title: "Personal"))
        let work = store.categories[1]
        let personal = store.categories[2]
        precondition(store.addCategory(title: "Fourth"))
        let fourth = store.categories[3]
        precondition(store.mainCategories.count == 3)
        precondition(store.moreCategories == [fourth])
        precondition(!store.setMain(fourth, enabled: true))
        precondition(store.setMain(.today, enabled: false))
        precondition(store.setMain(fourth, enabled: true))
        precondition(store.mainCategories == [work, personal, fourth])
        precondition(store.moreCategories == [.today])
        let pinnedRestart = TaskStore(persistence: persistence)
        precondition(pinnedRestart.mainCategoryIDs == store.mainCategoryIDs)
        precondition(pinnedRestart.categories.count == 4)
        precondition(!store.renameCategory(.today, title: "Changed"))
        precondition(!store.renameCategory(work, title: "personal"))
        precondition(!store.removeCategory(.today))
        precondition(store.renameCategory(work, title: "Studio"))
        precondition(TaskStore(persistence: persistence).categories[1].title == "Studio")
        precondition(!store.add(title: " \n ", category: .today))
        precondition(store.add(title: "  Read  a book \n", category: .today))
        precondition(store.add(title: "Send proposal", category: work))
        precondition(store.add(title: "Walk", category: .today))
        precondition(store.add(title: "Shop", category: personal))
        precondition(store.items(in: .today).count == 2)
        precondition(store.items(in: work).count == 1)
        precondition(store.items(in: personal).count == 1)
        let read = store.items(in: .today)[0]
        precondition(read.title == "Read  a book")
        store.toggle(read.id)
        precondition(store.items(in: .today, showCompleted: false).count == 1)
        precondition(store.items(in: .today).last?.id == read.id)
        store.toggle(read.id)
        store.move(in: .today, from: IndexSet(integer: 0), to: 2)
        precondition(store.items(in: .today).last?.id == read.id)
        precondition(store.edit(read.id, title: "Read tonight", category: personal))
        precondition(store.items(in: .today).count == 1)
        precondition(store.items(in: personal).count == 2)
        store.delete(read)
        precondition(!store.tasks.contains(where: { $0.id == read.id }))
        store.undoDelete()
        precondition(store.tasks.contains(where: { $0.id == read.id }))
        let reopened = TaskStore(persistence: persistence)
        precondition(reopened.tasks == store.tasks)
        print("PASS: validation, trimming, category isolation, completion, reopening, reordering, editing, deletion, undo, restart persistence")

        precondition(store.removeCategory(personal))
        precondition(!store.tasks.contains { $0.category == personal })
        precondition(store.categories.count == 3)
        precondition(!store.mainCategoryIDs.contains(personal.id))
        precondition(TaskStore(persistence: persistence).tasks.count == store.tasks.count)
        precondition(store.addCategory(title: "Errands"))
        precondition(!store.addCategory(title: " "))
        for index in 0..<8 { precondition(store.addCategory(title: "Extra \(index)")) }
        precondition(store.categories.count == 12)
        let manyRestart = TaskStore(persistence: persistence)
        precondition(manyRestart.categories.count == 12)
        precondition(manyRestart.mainCategories.count == 3)
        precondition(manyRestart.moreCategories.count == 9)
        for id in Array(store.mainCategoryIDs.dropFirst()) {
            precondition(store.setMain(store.categories.first { $0.id == id }!, enabled: false))
        }
        precondition(!store.setMain(store.mainCategories[0], enabled: false))
        print("PASS: unlimited categories, three main slots, More overflow, swapping/unpinning Today, persistent selection, safe removal")

        let lastViewPersistence = TaskPersistence(url: folder.appendingPathComponent("last-view.json"))
        try lastViewPersistence.save([])
        let lastView = TaskStore(persistence: lastViewPersistence)
        for title in ["A", "B", "Overflow"] { precondition(lastView.addCategory(title: title)) }
        let overflow = lastView.moreCategories[0]
        precondition(lastView.selectCategory(overflow))
        precondition(lastView.canDeleteCompletedCategory(overflow))
        lastView.add(title: "First", category: overflow)
        lastView.add(title: "Second", category: overflow)
        lastView.add(title: "Keep Today", category: .today)
        let overflowItems = lastView.items(in: overflow)
        lastView.toggle(overflowItems[0].id)
        precondition(!lastView.canDeleteCompletedCategory(overflow))
        precondition(!lastView.deleteCompletedCategory(overflow))
        lastView.toggle(overflowItems[1].id)
        let restoredView = TaskStore(persistence: lastViewPersistence)
        precondition(restoredView.selectedCategory == overflow)
        precondition(restoredView.moreCategories.contains(overflow))
        precondition(restoredView.items(in: overflow).map(\.title) == ["First", "Second"])
        precondition(restoredView.canDeleteCompletedCategory(overflow))
        let originalItems = restoredView.items(in: overflow)
        precondition(restoredView.deleteCompletedCategory(overflow))
        precondition(!restoredView.categories.contains(overflow))
        precondition(!restoredView.tasks.contains { $0.category == overflow })
        precondition(restoredView.items(in: .today).count == 1)
        precondition(restoredView.selectedCategory == .today)
        precondition(TaskStore(persistence: lastViewPersistence).selectedCategory == .today)
        precondition(!TaskStore(persistence: lastViewPersistence).categories.contains(overflow))
        restoredView.undoCategoryDeletion()
        precondition(restoredView.selectedCategory == overflow)
        precondition(restoredView.items(in: overflow) == originalItems)
        precondition(restoredView.moreCategories.contains(overflow))
        precondition(TaskStore(persistence: lastViewPersistence).selectedCategory == overflow)
        restoredView.toggle(restoredView.items(in: .today)[0].id)
        precondition(!restoredView.canDeleteCompletedCategory(.today))
        precondition(!restoredView.deleteCompletedCategory(.today))
        print("PASS: last-view restoration from More, empty or all-done deletion, partial/Today protection, undo with task IDs/order preserved")

        let emptyStore = TaskStore(persistence: TaskPersistence(url: folder.appendingPathComponent("empty-category.json")))
        precondition(emptyStore.addCategory(title: "Empty"))
        let emptyCategory = emptyStore.categories.last!
        precondition(emptyStore.canDeleteCompletedCategory(emptyCategory))
        precondition(emptyStore.add(title: "Open task", category: emptyCategory))
        precondition(!emptyStore.canDeleteCompletedCategory(emptyCategory))
        emptyStore.delete(emptyStore.items(in: emptyCategory)[0])
        precondition(emptyStore.canDeleteCompletedCategory(emptyCategory))
        precondition(emptyStore.deleteCompletedCategory(emptyCategory))
        precondition(!emptyStore.categories.contains(emptyCategory))
        precondition(!emptyStore.canDeleteCompletedCategory(.today))
        emptyStore.undoCategoryDeletion()
        precondition(emptyStore.categories.contains(emptyCategory))
        print("PASS: an empty category can be deleted (and undone); open tasks and Today still protect it")

        let memory = MemoryMirror()
        let mirrored = TaskPersistence(url: folder.appendingPathComponent("mirrored.json"), mirror: memory)
        let beforeReinstall = TaskStore(persistence: mirrored)
        precondition(beforeReinstall.add(title: "Typed by hand", category: .today))
        precondition(beforeReinstall.addCategory(title: "Gym"))
        let handTasks = beforeReinstall.tasks
        try FileManager.default.removeItem(at: mirrored.url)
        let afterReinstall = TaskStore(persistence: mirrored)
        precondition(afterReinstall.tasks == handTasks)
        precondition(afterReinstall.tasks.count == 5)
        precondition(afterReinstall.categories.map(\.title) == ["Today", "Gym"])
        precondition(FileManager.default.fileExists(atPath: mirrored.url.path))
        let nothingToRestore = TaskStore(persistence: TaskPersistence(url: folder.appendingPathComponent("fresh.json"), mirror: MemoryMirror()))
        precondition(nothingToRestore.tasks.count == 4)
        print("PASS: after a reinstall (file gone, Keychain copy kept) typed tasks and categories return without re-seeding starters")

        let legacyPersistence = TaskPersistence(url: folder.appendingPathComponent("legacy.json"))
        var oldCompleted = TaskItem(title: "Old work task", category: .work, order: 0)
        oldCompleted.isCompleted = true
        let unknownTask = TaskItem(title: "Unknown task", category: .legacy("unknown"), order: 1)
        try JSONEncoder().encode([oldCompleted, unknownTask]).write(to: legacyPersistence.url)
        let legacyStore = TaskStore(persistence: legacyPersistence)
        precondition(legacyStore.categories.map(\.id) == ["today", "work"])
        precondition(legacyStore.tasks[1].category == .today)
        precondition(legacyStore.tasks[0].completedAt != nil)
        let migratedTimestamp = legacyStore.tasks[0].completedAt
        precondition(TaskStore(persistence: legacyPersistence).tasks[0].completedAt == migratedTimestamp)
        print("PASS: legacy category migration, unknown category recovery, completed timestamp backfill persists once")

        let timedPersistence = TaskPersistence(url: folder.appendingPathComponent("timed.json"))
        try timedPersistence.save([])
        let timed = TaskStore(persistence: timedPersistence)
        timed.add(title: "Timed task", category: .today)
        timed.add(title: "Keep tomorrow too", category: .today)
        let timedID = timed.tasks[0].id
        let checkedAt = Date(timeIntervalSince1970: 1_800_000_000)
        timed.toggle(timedID, at: checkedAt)
        precondition(!timed.tasks[0].isArchived(at: checkedAt.addingTimeInterval(599)))
        precondition(timed.tasks[0].isArchived(at: checkedAt.addingTimeInterval(600)))
        precondition(!timed.tasks[1].isArchived(at: checkedAt.addingTimeInterval(86400 * 30)))
        let timedRestart = TaskStore(persistence: timedPersistence)
        precondition(timedRestart.tasks[0].isArchived(at: checkedAt.addingTimeInterval(601)))
        timedRestart.toggle(timedID, at: checkedAt.addingTimeInterval(700))
        precondition(timedRestart.tasks[0].completedAt == nil)
        precondition(!timedRestart.tasks[0].isArchived(at: checkedAt.addingTimeInterval(900)))
        timedRestart.toggle(timedID, at: checkedAt.addingTimeInterval(1000))
        precondition(!timedRestart.tasks[0].isArchived(at: checkedAt.addingTimeInterval(1599)))
        precondition(timedRestart.tasks[0].isArchived(at: checkedAt.addingTimeInterval(1600)))
        print("PASS: exact ten-minute boundary, restart, reopen/reset timer, no midnight expiration")

        timedRestart.add(title: "Third", category: .today)
        timedRestart.add(title: "Fourth", category: .today)
        let ids = timedRestart.tasks.dropFirst().map(\.id)
        timedRestart.move(in: .today, from: IndexSet(integer: 0), to: 3, visibleIDs: ids)
        let ordered = timedRestart.items(in: .today, sortingCompleted: false)
        precondition(ordered[0].id == timedID)
        precondition(ordered.last?.id == ids[0])
        print("PASS: reordering visible tasks preserves archived task positions")

        try Data("broken json".utf8).write(to: persistence.url)
        let recovered = TaskStore(persistence: persistence)
        precondition(recovered.tasks.isEmpty && recovered.errorMessage != nil)
        let files = try FileManager.default.contentsOfDirectory(at: folder, includingPropertiesForKeys: nil)
        let backup = files.first(where: { $0.lastPathComponent.contains("recovery-") })!
        let recoveredBytes = try String(contentsOf: backup, encoding: .utf8)
        precondition(recoveredBytes == "broken json")
        precondition(recovered.add(title: "Fresh task", category: .today))
        print("PASS: corrupt data backed up before new saves")

        let blocked = folder.appendingPathComponent("not-a-directory")
        try Data().write(to: blocked)
        let failed = TaskStore(persistence: TaskPersistence(url: blocked.appendingPathComponent("tasks.json")))
        precondition(!failed.add(title: "Cannot save", category: .today))
        precondition(failed.tasks.isEmpty && failed.errorMessage != nil)
        print("PASS: failed writes leave state unchanged and surface an error")
    }
}
